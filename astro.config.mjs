// @ts-check
import { defineConfig } from "astro/config";
import react from "@astrojs/react";
import sitemap from "@astrojs/sitemap";
import tailwindcss from "@tailwindcss/vite";
import legacyRedirects from "./scripts/migrate/redirects.json" with { type: "json" };

/*
 * Pages retired since the migration. Listed after the legacy entries so they
 * replace any that pointed at the old page.
 */
const retired = {
  // No general projects index any more: each section has its own.
  "/projets": "/projets/edition/",
  "/fr/projets": "/projets/edition/",
  "/en/projets": "/en/projets/edition/",
};

/*
 * Old Rails URLs -> new URLs, generated by scripts/migrate (meta-refresh stubs
 * in static output). An entry that points at its own address plus a trailing
 * slash is dropped: Astro lets a redirect win over the page it names, which
 * would turn that page into a stub that refreshes to itself.
 */
const redirects = Object.fromEntries(
  Object.entries({ ...legacyRedirects, ...retired }).filter(
    ([from, to]) => `${from.replace(/\/$/, "")}/` !== to
  )
);

export default defineConfig({
  // The media bucket, by its global and regional addresses (old images use the
  // first, CMS uploads the second). Lets the build read image sizes from it.
  image: {
    domains: [
      "nicolashubert-graphiste-production.s3.amazonaws.com",
      "nicolashubert-graphiste-production.s3.us-east-1.amazonaws.com",
    ],
  },
  site: "https://nicolashubert-graphiste.com",
  output: "static",
  trailingSlash: "always",
  prefetch: { prefetchAll: true, defaultStrategy: "hover" },
  i18n: {
    defaultLocale: "fr",
    locales: ["fr", "en"],
    routing: { prefixDefaultLocale: false },
  },
  integrations: [
    react(),
    sitemap({ filter: (page) => !page.includes("/admin/") }),
  ],
  vite: { plugins: [tailwindcss()] },
  redirects,
});
